"""``agenttruth scenarios export --format posthog-tasks-v2``: the catalog as PostHog ``tasks.yaml`` v2.

Exact-answer, planted-cause and round-trip-agent scenarios become benchmark tasks with PostHog's
six fields only (ADR-0007); round-trip-scripted cases are scripted, not agent tasks, and are left
out. The file validates against the vendored ``services/mcp/evals/benchmark/schema.ts``.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from agenttruth.evidence.models import Catalog, RSSpec
from agenttruth.evidence.read import load_yaml

__all__ = ["FORMATS", "export_posthog_tasks_v2", "render_posthog_tasks_v2"]

FORMATS = ("posthog-tasks-v2",)
_HEADER = (
    "# Generated by `agenttruth scenarios export --format posthog-tasks-v2` from {catalog}.\n"
    "# AgentTruth scenarios as PostHog MCP benchmark tasks (tasks.yaml version 2). Do not edit.\n"
)


def render_posthog_tasks_v2(catalog: Catalog, source: str) -> str:
    """Return the ``tasks.yaml`` v2 text for ``catalog`` (deterministic; tasks in catalog order)."""
    tasks = [
        {
            "id": s.id,
            "category": s.category,
            "intent": s.intent,
            "expected_tools": list(s.expected_tools),
            "acceptable_tools": list(s.acceptable_tools),
            "success_criteria": s.success_criteria,
        }
        for s in catalog.scenarios
        if not isinstance(s.agenttruth, RSSpec)
    ]
    document = {"version": 2, "fixtures": {"feature_flags": [], "absent_feature_flags": []}, "tasks": tasks}
    body: str = yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=1_000_000)
    return _HEADER.format(catalog=source) + body


def export_posthog_tasks_v2(catalog_path: Path, out: Path) -> int:
    """Write the export of ``catalog_path`` to ``out``; returns the number of tasks written."""
    catalog = Catalog.model_validate(load_yaml(catalog_path))
    text = render_posthog_tasks_v2(catalog, catalog_path.as_posix())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return sum(1 for s in catalog.scenarios if not isinstance(s.agenttruth, RSSpec))
